"""exp2 LUT generator (wtvco_audio_process.md §1.6).

LUT[i] = round(K * 2^10 * 2^(i/1024)),  i = 0..1024  (1024 entries + 1 sentinel)
K      = f_C0 * 2^32 / SAMPLE_RATE

The x2^10 factor pre-applies the shift for the top octave (pitch integer part 10),
so the runtime only ever shifts right by (10 - integer part).

Usage:  python tools/gen_exp2_lut.py            (writes ../exp2_lut.h next to the sketch)
"""
import math
import os
import sys

SAMPLE_RATE = 96000
F_C0 = 440.0 * 2.0 ** (-57.0 / 12.0)  # 16.351597831 Hz (A4 = 440 Hz, scientific pitch notation)
LUT_BITS = 10                          # 1024 entries
LUT_SIZE = 1 << LUT_BITS
PRESHIFT = 10                          # = integer part of PITCH_MAX_Q

K = F_C0 * 2.0 ** 32 / SAMPLE_RATE


def build():
    lut = [round(K * 2.0 ** PRESHIFT * 2.0 ** (i / LUT_SIZE)) for i in range(LUT_SIZE + 1)]
    assert lut[-1] == round(K * 2.0 ** (PRESHIFT + 1)), "sentinel must equal K * 2^11"
    assert lut[-1] < 2 ** 31, "LUT values must fit in 31 bits"
    return lut


def write_header(path, lut):
    lines = []
    lines.append("// Generated by tools/gen_exp2_lut.py -- do not edit by hand.")
    lines.append("// exp2 LUT: round(K * 2^10 * 2^(i/1024)), i = 0..1024 (last entry = sentinel K * 2^11)")
    lines.append(f"// f_C0 = {F_C0:.9f} Hz, SAMPLE_RATE = {SAMPLE_RATE}, K = f_C0 * 2^32 / SAMPLE_RATE = {K:.6f}")
    lines.append("#pragma once")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append(f"#define EXP2_LUT_BITS      {LUT_BITS}")
    lines.append(f"#define EXP2_LUT_SIZE      {LUT_SIZE}")
    lines.append(f"#define EXP2_LUT_PRESHIFT  {PRESHIFT}")
    lines.append(f"#define EXP2_LUT_SAMPLE_RATE {SAMPLE_RATE}")
    lines.append("")
    lines.append("// Defined in exactly one translation unit (pitch.cpp) via EXP2_LUT_IMPLEMENTATION.")
    lines.append("// That unit may define EXP2_LUT_ATTR (e.g. a RAM section); default: plain const (flash).")
    lines.append("extern const uint32_t EXP2_LUT[EXP2_LUT_SIZE + 1];")
    lines.append("")
    lines.append("#ifdef EXP2_LUT_IMPLEMENTATION")
    lines.append("#ifndef EXP2_LUT_ATTR")
    lines.append("#define EXP2_LUT_ATTR")
    lines.append("#endif")
    lines.append(f"const uint32_t EXP2_LUT[EXP2_LUT_SIZE + 1] EXP2_LUT_ATTR = {{")
    per_line = 8
    for i in range(0, len(lut), per_line):
        chunk = ", ".join(f"{v:10d}u" for v in lut[i:i + per_line])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("#endif")
    lines.append("")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "exp2_lut.h")
    lut = build()
    write_header(out, lut)

    # Quick self-check: worst LUT error (before the right shift) against exact exp2, in cents.
    worst = 0.0
    for p in range(0, 1 << 16):                  # every Q16.16 fractional value
        idx, frac = p >> 6, p & 63
        a, b = lut[idx], lut[idx + 1]
        v = a + (((b - a) * frac) >> 6)
        exact = K * 2.0 ** PRESHIFT * 2.0 ** (p / 65536.0)
        worst = max(worst, abs(1200.0 * math.log2(v / exact)))
    print(f"wrote {os.path.normpath(out)}")
    print(f"  K = {K:.6f}, LUT[0] = {lut[0]}, sentinel = {lut[-1]}")
    print(f"  worst LUT error (pre-shift) = {worst:.6f} cent")


if __name__ == "__main__":
    main()
