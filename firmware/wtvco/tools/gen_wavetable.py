"""Wavetable generator (wtvco_audio_process.md §1.7).

- Mipmap levels are computed from the rule (not hard-coded):
    max harmonic = min(floor(NYQUIST / (f_C0 * 2^(L+1))), BASE_LEN/2 - 1)
    table length = smallest power of 2 >= 8 * max harmonic, clamped to [256, 2048]
- Band-limiting is FFT based: every frame is transformed once, harmonics above the level's
  maximum (and DC) are zeroed, and the inverse transform is taken at the level's length.
- One normalisation factor for all frames and levels (peak within int16 full scale),
  so the volume does not change between levels.
- Each table is stored with one extra sample (a copy of sample 0) for wrap-free interpolation.

Frame contents come from wt_frames.py (edit that file to change the waveforms).

Usage:  python tools/gen_wavetable.py           (writes ../wavetable.h and tools/wavetable_preview.svg)
"""
import math
import os
import sys

import numpy as np

import wt_frames

SAMPLE_RATE = 96000
NYQUIST = SAMPLE_RATE / 2
F_C0 = 440.0 * 2.0 ** (-57.0 / 12.0)
NUM_LEVELS = 11                     # pitch integer part 0..10
BASE_LEN = wt_frames.BASE_LEN       # 2048
MIN_LEN = 256
OVERSAMPLE = 8                      # table length >= 8 * max harmonic (linear-interpolation images)
FULL_SCALE = 32767


def level_params():
    levels = []
    for L in range(NUM_LEVELS):
        upper = F_C0 * 2.0 ** (L + 1)
        maxh = min(int(math.floor(NYQUIST / upper)), BASE_LEN // 2 - 1)
        n = 1
        while n < OVERSAMPLE * maxh:
            n <<= 1
        n = max(MIN_LEN, min(BASE_LEN, n))
        levels.append({"level": L, "f_lo": F_C0 * 2.0 ** L, "f_hi": upper, "maxh": maxh,
                       "len": n, "log2len": n.bit_length() - 1})
    return levels


def build():
    levels = level_params()
    frames = wt_frames.get_frames()
    if len(frames) != wt_frames.NUM_FRAMES:
        raise ValueError("wt_frames.get_frames() returned the wrong number of frames")

    # float tables[frame][level]
    tables = []
    for x in frames:
        x = np.asarray(x, dtype=float)
        if len(x) != BASE_LEN:
            raise ValueError(f"each frame must have {BASE_LEN} samples")
        X = np.fft.rfft(x)
        per_level = []
        for lv in levels:
            n, h = lv["len"], lv["maxh"]
            Y = np.zeros(n // 2 + 1, dtype=complex)
            Y[1:h + 1] = X[1:h + 1]                      # DC (bin 0) and everything above h stay 0
            per_level.append(np.fft.irfft(Y, n=n) * (n / BASE_LEN))
        tables.append(per_level)

    peak = max(np.max(np.abs(t)) for fr in tables for t in fr)
    scale = FULL_SCALE / peak

    q = [[np.clip(np.round(t * scale), -FULL_SCALE, FULL_SCALE).astype(np.int16) for t in fr]
         for fr in tables]
    return levels, q, scale


def verify(levels, q):
    """Check band limit and DC on the quantised tables. Returns worst out-of-band level in dBFS."""
    worst_oob = -math.inf
    worst_dc = 0.0
    for fr in q:
        for lv, t in zip(levels, fr):
            S = np.abs(np.fft.rfft(t.astype(float))) / (len(t) / 2) / FULL_SCALE
            oob = S[lv["maxh"] + 1:]
            if len(oob):
                worst_oob = max(worst_oob, 20 * math.log10(max(np.max(oob), 1e-12)))
            worst_dc = max(worst_dc, abs(float(np.mean(t))))
    return worst_oob, worst_dc


def write_header(path, levels, q):
    offsets, off = [], 0
    for lv in levels:
        offsets.append(off)
        off += lv["len"] + 1                             # +1 = wrap sample
    stride = off

    L = []
    L.append("// Generated by tools/gen_wavetable.py -- do not edit by hand.")
    L.append("// Frame contents: tools/wt_frames.py")
    L.append("// Layout: WT_DATA[frame][WT_LEVEL_OFFSET[level] + i], i = 0..len (sample len = copy of sample 0)")
    L.append("#pragma once")
    L.append("#include <stdint.h>")
    L.append("")
    L.append(f"#define WT_NUM_FRAMES   {len(q)}")
    L.append(f"#define WT_NUM_LEVELS   {len(levels)}")
    L.append(f"#define WT_FRAME_STRIDE {stride}")
    L.append("")
    L.append("//  level  f_lo(Hz)   f_hi(Hz)   maxh  len")
    for lv in levels:
        L.append(f"//  {lv['level']:5d}  {lv['f_lo']:9.2f}  {lv['f_hi']:9.2f}  {lv['maxh']:4d}  {lv['len']:4d}")
    L.append("")
    L.append("static const uint32_t WT_LEVEL_OFFSET[WT_NUM_LEVELS] = { "
             + ", ".join(str(o) for o in offsets) + " };")
    L.append("static const uint8_t  WT_LEVEL_LOG2LEN[WT_NUM_LEVELS] = { "
             + ", ".join(str(lv["log2len"]) for lv in levels) + " };")
    L.append("static const uint16_t WT_LEVEL_MAXH[WT_NUM_LEVELS] = { "
             + ", ".join(str(lv["maxh"]) for lv in levels) + " };")
    L.append("")
    L.append("// Defined in exactly one translation unit (oscillator.cpp) via WAVETABLE_IMPLEMENTATION.")
    L.append("// That unit may define WT_DATA_ATTR (e.g. a RAM section); default: plain const (flash).")
    L.append("extern const int16_t WT_DATA[WT_NUM_FRAMES][WT_FRAME_STRIDE];")
    L.append("")
    L.append("#ifdef WAVETABLE_IMPLEMENTATION")
    L.append("#ifndef WT_DATA_ATTR")
    L.append("#define WT_DATA_ATTR")
    L.append("#endif")
    L.append("const int16_t WT_DATA[WT_NUM_FRAMES][WT_FRAME_STRIDE] WT_DATA_ATTR = {")
    per_line = 16
    for f, fr in enumerate(q):
        L.append(f"  {{ // frame {f}")
        for lv, t in zip(levels, fr):
            L.append(f"    // level {lv['level']} (len {lv['len']} + 1)")
            full = np.concatenate([t, t[:1]])
            for i in range(0, len(full), per_line):
                L.append("    " + ",".join(f"{int(v):6d}" for v in full[i:i + per_line]) + ",")
        L.append("  },")
    L.append("};")
    L.append("#endif")
    L.append("")
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(L))
    return stride


def write_preview_svg(path, levels, q, show_levels=(0, 3, 5, 7, 9, 10)):
    cw, ch, pad, lab = 120, 44, 6, 64
    rows, cols = len(q), len(show_levels)
    W, H = lab + cols * (cw + pad), 24 + rows * (ch + pad)
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" '
           f'font-family="sans-serif" font-size="11">',
           f'<rect width="{W}" height="{H}" fill="#fff"/>']
    for c, lvi in enumerate(show_levels):
        lv = levels[lvi]
        out.append(f'<text x="{lab + c * (cw + pad) + cw / 2}" y="14" text-anchor="middle">'
                   f'L{lvi} (h&#8804;{lv["maxh"]}, n={lv["len"]})</text>')
    for r, fr in enumerate(q):
        y0 = 24 + r * (ch + pad)
        out.append(f'<text x="4" y="{y0 + ch / 2 + 4}">frame {r}</text>')
        for c, lvi in enumerate(show_levels):
            x0 = lab + c * (cw + pad)
            t = fr[lvi].astype(float) / FULL_SCALE
            xs = np.linspace(x0, x0 + cw, len(t))
            ys = y0 + ch / 2 - t * (ch / 2 - 2)
            pts = " ".join(f"{a:.1f},{b:.1f}" for a, b in zip(xs, ys))
            out.append(f'<rect x="{x0}" y="{y0}" width="{cw}" height="{ch}" fill="#f4f4f4"/>')
            out.append(f'<line x1="{x0}" y1="{y0 + ch / 2}" x2="{x0 + cw}" y2="{y0 + ch / 2}" stroke="#ccc"/>')
            out.append(f'<polyline points="{pts}" fill="none" stroke="#1565c0" stroke-width="1"/>')
    out.append("</svg>")
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(out))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "wavetable.h")
    levels, q, scale = build()
    stride = write_header(out, levels, q)
    write_preview_svg(os.path.join(here, "wavetable_preview.svg"), levels, q)
    oob, dc = verify(levels, q)

    print(f"wrote {os.path.normpath(out)}")
    print(" level  f_lo(Hz)   f_hi(Hz)   maxh   len")
    for lv in levels:
        print(f"  {lv['level']:4d}  {lv['f_lo']:9.2f}  {lv['f_hi']:9.2f}  {lv['maxh']:5d}  {lv['len']:5d}")
    print(f"  frame stride = {stride} samples, total = {stride * len(q) * 2} bytes")
    print(f"  normalisation scale = {scale:.3f}, peak = {max(int(np.max(np.abs(t))) for fr in q for t in fr)}")
    print(f"  worst out-of-band component = {oob:.1f} dBFS (quantisation floor)")
    print(f"  worst DC = {dc:.3f} LSB")


if __name__ == "__main__":
    main()
